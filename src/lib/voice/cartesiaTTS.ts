/**
 * Convert PCM16LE sample to μ-law.
 *
 * Twilio expects G.711 μ-law 8 kHz audio.
 */
function linearToMulaw(sample: number): number {
  const BIAS = 0x84;
  const CLIP = 32635;

  let pcm = Math.max(-CLIP, Math.min(CLIP, sample));

  let sign = 0;

  if (pcm < 0) {
    sign = 0x80;
    pcm = -pcm;
  }

  pcm += BIAS;

  let exponent = 7;
  let mask = 0x4000;

  while (exponent > 0 && (pcm & mask) === 0) {
    exponent--;
    mask >>= 1;
  }

  const mantissa = (pcm >> (exponent + 3)) & 0x0f;

  return ~(sign | (exponent << 4) | mantissa) & 0xff;
}

function pcmToMulaw(pcm: Buffer): Buffer {
  const sampleCount = Math.floor(pcm.length / 2);
  const output = Buffer.alloc(sampleCount);

  for (let i = 0; i < sampleCount; i++) {
    const sample = pcm.readInt16LE(i * 2);
    output[i] = linearToMulaw(sample);
  }

  return output;
}

