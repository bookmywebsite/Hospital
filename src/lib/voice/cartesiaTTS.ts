/**
 * Cartesia Live TTS
 *
 * Designed as a drop-in replacement for SarvamLiveTTS.
 *
 * Audio generated by Cartesia:
 *
 *   PCM16LE / 8 kHz
 *
 * Output:
 *
 *   Exotel -> PCM16LE / 8 kHz
 *   Twilio -> μ-law / 8 kHz
 */
export class CartesiaLiveTTS {
  private client: Cartesia;

  private ws: Awaited<ReturnType<Cartesia["tts"]["websocket"]>> | null = null;

  private voiceId: string;
  private language: string;

  private onAudioChunk: (chunk: Buffer) => void;
  private onComplete?: () => void;
  private onError?: (error: Error) => void;

  private outputFormat: TTSOutputFormat;

  private closed = false;
  private generationActive = false;
  private generationId = 0;

  constructor(
    voiceId: string,
    language: string,
    onAudioChunk: (chunk: Buffer) => void,
    onComplete?: () => void,
    onError?: (error: Error) => void,
    outputFormat: TTSOutputFormat = "mulaw8k",
  ) {
    const apiKey = process.env.CARTESIA_API_KEY;

    if (!apiKey) {
      throw new Error("Missing CARTESIA_API_KEY");
    }

    this.client = new Cartesia({
      apiKey,
    });

    this.voiceId = voiceId;
    this.language = language;

    this.onAudioChunk = onAudioChunk;
    this.onComplete = onComplete;
    this.onError = onError;
    this.outputFormat = outputFormat;
  }

  /**
   * Establish/reuse the Cartesia WebSocket connection.
   *
   * Keeping the WebSocket open avoids paying the connection
   * setup latency for every sentence.
   */
  private async ensureConnection() {
    if (this.closed) {
      throw new Error("Cartesia TTS has been closed");
    }

    if (this.ws) {
      return this.ws;
    }

    this.ws = await this.client.tts.websocket();

    return this.ws;
  }

  /**
   * Speak text and stream audio chunks immediately.
   */
  async speak(text: string, isEndingCheck?: () => boolean): Promise<void> {
    if (!text?.trim()) {
      return;
    }

    if (this.closed) {
      return;
    }

    if (isEndingCheck?.()) {
      return;
    }

    const currentGenerationId = ++this.generationId;

    this.generationActive = true;

    try {
      const ws = await this.ensureConnection();

      if (this.closed || isEndingCheck?.()) {
        return;
      }

      const cartesiaLanguage = getCartesiaLanguage(this.language);

      const response = ws.generate({
        model_id: "sonic-3.5",

        transcript: text,

        voice: {
          mode: "id",
          id: this.getVoiceId(),
        },

        language: cartesiaLanguage,

        output_format: {
          container: "raw",
          encoding: "pcm_s16le",
          sample_rate: 8000,
        },
      });

      let receivedAudio = false;

      for await (const event of response) {
        /**
         * If another response started, the call was interrupted.
         */
        if (this.closed || currentGenerationId !== this.generationId || isEndingCheck?.()) {
          break;
        }

        if (event.type === "chunk" && event.data) {
          receivedAudio = true;

          // Cartesia WebSocket sends base64-encoded audio.
          const pcmAudio = Buffer.from(event.data, "base64");

          const audio = this.outputFormat === "mulaw8k" ? pcmToMulaw(pcmAudio) : pcmAudio;

          this.onAudioChunk(audio);
        }

        if (event.type === "error") {
          throw new Error(`Cartesia TTS error: ${JSON.stringify(event)}`);
        }

        if (event.type === "done") {
          break;
        }
      }

      if (
        receivedAudio &&
        !this.closed &&
        currentGenerationId === this.generationId &&
        !isEndingCheck?.()
      ) {
        this.onComplete?.();
      }
    } catch (error) {
      if (this.closed) {
        return;
      }

      /**
       * Ignore errors caused by an intentional interruption.
       */
      if (currentGenerationId !== this.generationId) {
        return;
      }

      const err = error instanceof Error ? error : new Error(String(error));

      console.error("[Cartesia TTS] Error:", err);

      this.onError?.(err);

      throw err;
    } finally {
      if (currentGenerationId === this.generationId) {
        this.generationActive = false;
      }
    }
  }

  /**
   * Resolve the Cartesia voice ID.
   */
  private getVoiceId(): string {
    const envKeyMap: Record<string, string> = {
      "en-IN": "CARTESIA_VOICE_EN",
      "hi-IN": "CARTESIA_VOICE_HI",
      "kn-IN": "CARTESIA_VOICE_KN",
      "ta-IN": "CARTESIA_VOICE_TA",
      "te-IN": "CARTESIA_VOICE_TE",
      "ml-IN": "CARTESIA_VOICE_ML",
      "mr-IN": "CARTESIA_VOICE_MR",
      "bn-IN": "CARTESIA_VOICE_BN",
      "gu-IN": "CARTESIA_VOICE_GU",
      "pa-IN": "CARTESIA_VOICE_PA",
      "or-IN": "CARTESIA_VOICE_OR",
    };

    const envKey = envKeyMap[this.language];
    const configuredVoice = envKey ? process.env[envKey] : undefined;

    if (configuredVoice) {
      return configuredVoice;
    }

    if (this.voiceId && !this.voiceId.endsWith("-IN")) {
      return this.voiceId;
    }

    const genericVoice = process.env.CARTESIA_VOICE_ID;

    if (genericVoice) {
      return genericVoice;
    }

    throw new Error(
      `No Cartesia voice configured for language ${this.language}. ` +
        `Set CARTESIA_VOICE_${this.language.split("-")[0].toUpperCase()} or CARTESIA_VOICE_ID.`,
    );
  }

  /**
   * Change language/voice.
   *
   * Kept compatible with the existing Sarvam interface.
   */
  changeVoice(voiceId: string, language?: string): void {
    this.voiceId = voiceId;

    if (language) {
      this.language = language;
    }
  }

  /**
   * Cancel the currently active generation.
   *
   * We invalidate the generation immediately.
   *
   * Closing the WebSocket also guarantees that any currently
   * streaming generation is stopped.
   */
  close(): void {
    this.generationId++;

    this.generationActive = false;

    if (this.ws) {
      try {
        this.ws.close();
      } catch {
        // Ignore close errors.
      }
    }

    this.ws = null;
  }

  /**
   * Alias used by existing code.
   */
  stop(): void {
    this.close();
  }

  /**
   * Alias used by existing code.
   */
  destroy(): void {
    this.close();
  }

  /**
   * Final cleanup.
   */
  async dispose(): Promise<void> {
    this.closed = true;

    this.generationId++;

    this.generationActive = false;

    if (this.ws) {
      try {
        this.ws.close();
      } catch {
        // Ignore close errors.
      }
    }

    this.ws = null;
  }

  /**
   * Compatibility with the existing Sarvam implementation.
   *
   * Cartesia receives plain text for this project.
   */
  async speakSSML(ssml: string, isEndingCheck?: () => boolean): Promise<void> {
    const text = ssml
      .replace(/<break[^>]*>/gi, " ")
      .replace(/<[^>]+>/g, "")
      .replace(/\s+/g, " ")
      .trim();

    if (!text) {
      return;
    }

    await this.speak(text, isEndingCheck);
  }

  isSpeaking(): boolean {
    return this.generationActive;
  }
}
